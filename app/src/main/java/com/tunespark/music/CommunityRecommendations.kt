package com.tunespark.music

import android.content.Context
import com.metrolist.innertube.YouTube
import com.metrolist.innertube.models.PlaylistItem
import com.metrolist.innertube.models.SongItem
import com.metrolist.innertube.models.WatchEndpoint
import com.tunespark.music.ui.screens.CommunityPlaylistData
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.async
import kotlinx.coroutines.awaitAll
import kotlinx.coroutines.coroutineScope
import kotlinx.coroutines.withContext
import kotlin.math.log10
import kotlin.math.pow
import kotlin.math.sqrt

/**
 * Taste-based community playlist recommendations.
 *
 * Nothing here reads the playlist title or author for ranking — a playlist is
 * judged purely by the songs it contains and how well those songs match the
 * listener's profile. Candidates are discovered from YouTube Music's own
 * mood/genre "Community playlists" shelves, so they carry whatever name their
 * curator gave them (often nothing to do with an artist). The profile is built
 * from the local listening history (recency weighted), liked songs and, when
 * those are thin, the signed-in YouTube Music signals. A content neighbourhood
 * is grown from the radio queue of the most-played songs so that similar-but-not
 * -identical artists can also match.
 */
object CommunityRecommendations {

    private const val MAX_RESULTS = 8
    private const val MAX_PAGE_FETCHES = 14
    private const val MAX_SEEDS = 4
    private const val MAX_GENRES = 12
    private const val MIN_TRACKS = 6
    private const val HALF_LIFE_DAYS = 21.0
    private const val DAY_MILLIS = 86_400_000.0

    private val PREFERRED_GENRES = listOf(
        "Chill",
        "Feel good",
        "Focus",
        "Workout",
        "Party",
        "Pop",
        "Rock",
        "Hip-hop",
        "R&B & soul",
        "Indie & alternative",
        "Dance & electronic",
        "Hindi",
    )

    private data class Profile(
        val songWeights: Map<String, Double>,
        val artistWeights: Map<String, Double>,
        val neighborhoodSongs: Map<String, Double>,
        val neighborhoodArtists: Map<String, Double>,
        val likedIds: Set<String>,
        val seedSongs: List<SongItem>,
    ) {
        val hasTaste: Boolean
            get() = songWeights.isNotEmpty() || artistWeights.isNotEmpty()
    }

    private class Candidate(
        val playlist: PlaylistItem,
        val affinity: Double,
        val views: Int,
    )

    private class Scored(
        val data: CommunityPlaylistData,
        val score: Double,
        val artistKeys: Set<String>,
        val author: String,
    )

    suspend fun recommend(context: Context, signedIn: Boolean): List<CommunityPlaylistData> =
        withContext(Dispatchers.IO) {
            try {
                val base = buildBaseProfile(context, signedIn)
                val neighborhood = if (base.seedSongs.isNotEmpty()) {
                    expandNeighborhood(base.seedSongs)
                } else {
                    emptyList()
                }
                val profile = base.copy(
                    neighborhoodSongs = neighborhood.flatMap { it.related }
                        .associate { it.first.id to it.second },
                    neighborhoodArtists = neighborhood.flatMap { it.artists }
                        .groupBy({ it.first }, { it.second })
                        .mapValues { (_, values) -> values.sum().coerceAtMost(1.0) },
                )

                val categories = fetchGenreCategories()
                if (categories.isEmpty()) return@withContext emptyList()

                val genreShelves = coroutineScope {
                    categories.map { category ->
                        async {
                            val result = YouTube.browse(category.browseId, category.params).getOrNull()
                                ?: return@async null
                            val songs = result.items
                                .firstOrNull { section ->
                                    section.title?.contains("song", ignoreCase = true) == true
                                }
                                ?.items?.filterIsInstance<SongItem>()
                                .orEmpty()
                            val community = result.items
                                .firstOrNull { section ->
                                    section.title?.contains("community", ignoreCase = true) == true
                                }
                                ?.items?.filterIsInstance<PlaylistItem>()
                                .orEmpty()
                                .filter { !it.isPodcast && !isAutoGenerated(it.id) }
                            GenreShelf(songs, community)
                        }
                    }.awaitAll().filterNotNull()
                }

                val rawAffinities = genreShelves.map { shelf ->
                    categoryAffinity(profile, shelf.songs)
                }
                val maxAffinity = rawAffinities.maxOrNull() ?: 0.0

                val seen = HashSet<String>()
                val byShelf = genreShelves.mapIndexedNotNull { index, shelf ->
                    val affinity = if (maxAffinity > 0.0) rawAffinities[index] / maxAffinity else 0.0
                    val list = shelf.community.mapNotNull { playlist ->
                        if (!seen.add(playlist.id)) return@mapNotNull null
                        Candidate(
                            playlist = playlist,
                            affinity = affinity,
                            views = parseViews(playlist.songCountText),
                        )
                    }
                    list.ifEmpty { null }
                }

                if (byShelf.isEmpty()) {
                    return@withContext fallbackPopular(genreShelves)
                }

                val preRanked = byShelf
                    .sortedByDescending { shelf -> shelf.first().affinity }
                    .flatMap { shelf -> shelf.sortedByDescending { preScore(it) }.take(3) }
                    .sortedByDescending { preScore(it) }
                    .take(MAX_PAGE_FETCHES)

                val fetched = coroutineScope {
                    preRanked.map { candidate ->
                        async {
                            val page = YouTube.playlist(candidate.playlist.id).getOrNull()
                                ?: return@async null
                            if (page.songs.size < MIN_TRACKS) return@async null
                            val playlist = page.playlist.copy(
                                thumbnail = page.playlist.thumbnail ?: candidate.playlist.thumbnail,
                                author = page.playlist.author ?: candidate.playlist.author,
                                songCountText = page.playlist.songCountText
                                    ?: candidate.playlist.songCountText,
                            )
                            val data = CommunityPlaylistData(playlist, page.songs)
                            Scored(
                                data = data,
                                score = scorePlaylist(data, profile) +
                                    8.0 * candidate.affinity +
                                    3.0 * popularity(candidate.views),
                                artistKeys = page.songs.flatMap { song ->
                                    song.artists.map { it.name.lowercase().trim() }
                                }.toSet(),
                                author = playlist.author?.name?.lowercase()?.trim().orEmpty(),
                            )
                        }
                    }.awaitAll().filterNotNull()
                }

                diversify(fetched)
            } catch (e: Exception) {
                e.printStackTrace()
                emptyList()
            }
        }

    private class MediaRow(
        val related: List<Pair<SongItem, Double>>,
        val artists: List<Pair<String, Double>>,
    )

    private class GenreShelf(
        val songs: List<SongItem>,
        val community: List<PlaylistItem>,
    )

    private class GenreCategory(
        val browseId: String,
        val params: String?,
    )

    private suspend fun buildBaseProfile(context: Context, signedIn: Boolean): Profile {
        val history = SessionManager.getLocalHistoryWithTimestamps(context)
        val now = System.currentTimeMillis()
        val songWeights = HashMap<String, Double>()
        val artistWeights = HashMap<String, Double>()
        val likedIds = LikedSongManager.likedMap.filterValues { it }.keys.toSet()

        history.asSequence()
            .distinctBy { it.first.id }
            .take(300)
            .forEachIndexed { index, (song, timestamp) ->
                if (song.id.isBlank() || song.id.startsWith("commentary_")) return@forEachIndexed
                val ageDays = ((now - timestamp) / DAY_MILLIS).coerceIn(0.0, 365.0)
                var weight = 0.5.pow(ageDays / HALF_LIFE_DAYS)
                weight /= 1.0 + index * 0.01
                if (song.id in likedIds) weight *= 2.2
                songWeights[song.id] = (songWeights[song.id] ?: 0.0) + weight
                addArtists(artistWeights, song, weight)
            }

        if (signedIn && history.size < 15) {
            YouTube.playlist("LM").getOrNull()?.songs.orEmpty().take(150)
                .forEachIndexed { index, song ->
                    if (song.id.isBlank() || song.id.startsWith("commentary_")) return@forEachIndexed
                    val boost = 0.9 / (1.0 + index * 0.01)
                    songWeights[song.id] = (songWeights[song.id] ?: 0.0) + boost
                    addArtists(artistWeights, song, boost)
                }
        }

        if (signedIn && history.size < 5) {
            YouTube.libraryRecentActivity().getOrNull()?.items
                ?.filterIsInstance<SongItem>()
                .orEmpty()
                .forEachIndexed { index, song ->
                    val weight = 0.7 / (1.0 + index * 0.08)
                    songWeights[song.id] = (songWeights[song.id] ?: 0.0) + weight
                    addArtists(artistWeights, song, weight)
                }
        }

        val normalizedSongs = normalize(songWeights)
        val normalizedArtists = normalize(artistWeights)
        val seeds = history.asSequence()
            .map { it.first }
            .filter { it.id in normalizedSongs }
            .distinctBy { it.id }
            .sortedByDescending { normalizedSongs[it.id] ?: 0.0 }
            .take(MAX_SEEDS)
            .toList()

        return Profile(
            songWeights = normalizedSongs,
            artistWeights = normalizedArtists,
            neighborhoodSongs = emptyMap(),
            neighborhoodArtists = emptyMap(),
            likedIds = likedIds,
            seedSongs = seeds,
        )
    }

    private suspend fun expandNeighborhood(seeds: List<SongItem>): List<MediaRow> =
        coroutineScope {
            seeds.take(MAX_SEEDS).mapIndexed { seedIndex, seed ->
                async {
                    val items = YouTube.next(WatchEndpoint(videoId = seed.id))
                        .getOrNull()?.items.orEmpty()
                    val seedWeight = 1.0 / (1.0 + seedIndex * 0.5)
                    val related = items.mapIndexedNotNull { rank, song ->
                        if (song.id.isBlank() || song.id == seed.id) return@mapIndexedNotNull null
                        song to seedWeight * 0.6 / (1.0 + rank * 0.05)
                    }
                    val artists = items.flatMap { song ->
                        song.artists.map { it.name.lowercase().trim() }
                    }.distinct().map { it to seedWeight * 0.5 }
                    MediaRow(related, artists)
                }
            }.awaitAll()
        }

    private suspend fun fetchGenreCategories(): List<GenreCategory> {
        val sections = YouTube.moodAndGenres().getOrNull() ?: return emptyList()
        val byTitle = sections.flatMap { it.items }
            .associateBy({ it.title.lowercase().trim() }, { it.endpoint })

        val selected = LinkedHashMap<String, GenreCategory>()
        PREFERRED_GENRES.forEach { name ->
            val endpoint = byTitle[name.lowercase()] ?: return@forEach
            selected[name] = GenreCategory(endpoint.browseId, endpoint.params)
        }
        if (selected.size < MAX_GENRES) {
            sections.flatMap { it.items }.forEach { item ->
                if (selected.size >= MAX_GENRES) return@forEach
                selected.putIfAbsent(item.title, GenreCategory(item.endpoint.browseId, item.endpoint.params))
            }
        }
        return selected.values.take(MAX_GENRES)
    }

    private fun categoryAffinity(profile: Profile, songs: List<SongItem>): Double {
        if (songs.isEmpty() || !profile.hasTaste) return 0.0
        var total = 0.0
        songs.forEach { song ->
            total += (profile.songWeights[song.id] ?: 0.0) +
                (profile.neighborhoodSongs[song.id] ?: 0.0) +
                bestArtistWeight(profile, song)
        }
        return total / songs.size
    }

    private fun bestArtistWeight(profile: Profile, song: SongItem): Double {
        var best = 0.0
        song.artists.forEach { artist ->
            val key = artist.name.lowercase().trim()
            val direct = profile.artistWeights[key] ?: 0.0
            val related = profile.neighborhoodArtists[key] ?: 0.0
            val value = if (direct > related) direct else related
            if (value > best) best = value
        }
        return best
    }

    private fun preScore(candidate: Candidate): Double =
        4.0 * candidate.affinity + popularity(candidate.views) * 1.5

    private fun popularity(views: Int): Double {
        if (views <= 0) return 0.0
        return (log10(views.toDouble() + 1.0) / 7.0).coerceIn(0.0, 1.0)
    }

    private fun scorePlaylist(data: CommunityPlaylistData, profile: Profile): Double {
        val songs = data.songs
        if (songs.isEmpty() || !profile.hasTaste) return 0.0
        val trackCount = songs.size.toDouble()

        var songHit = 0.0
        var likedHit = 0.0
        var directArtist = 0.0
        var artistAny = 0.0

        songs.forEach { song ->
            songHit += (profile.songWeights[song.id] ?: 0.0) +
                (profile.neighborhoodSongs[song.id] ?: 0.0)
            if (song.id in profile.likedIds) likedHit += 1.0

            var bestDirect = 0.0
            var bestAny = 0.0
            song.artists.forEach { artist ->
                val key = artist.name.lowercase().trim()
                val direct = profile.artistWeights[key] ?: 0.0
                val related = profile.neighborhoodArtists[key] ?: 0.0
                if (direct > bestDirect) bestDirect = direct
                val any = if (direct > related) direct else related
                if (any > bestAny) bestAny = any
            }
            directArtist += bestDirect
            artistAny += bestAny
        }

        val songScore = ((songHit / sqrt(trackCount)) / 2.5).coerceIn(0.0, 1.0)
        val likedScore = ((likedHit / trackCount) / 0.2).coerceIn(0.0, 1.0)
        val directArtistScore = ((directArtist / trackCount) / 0.6).coerceIn(0.0, 1.0)
        val neighborhoodScore =
            (((artistAny - directArtist).coerceAtLeast(0.0) / trackCount) / 0.6).coerceIn(0.0, 1.0)

        return 40.0 * songScore +
            22.0 * directArtistScore +
            18.0 * neighborhoodScore +
            12.0 * likedScore
    }

    private suspend fun fallbackPopular(shelves: List<GenreShelf>): List<CommunityPlaylistData> {
        val candidates = shelves.flatMap { it.community }
            .distinctBy { it.id }
            .sortedByDescending { parseViews(it.songCountText) }
            .take(MAX_PAGE_FETCHES)
        val fetched = coroutineScope {
            candidates.map { playlist ->
                async {
                    val page = YouTube.playlist(playlist.id).getOrNull() ?: return@async null
                    if (page.songs.size < MIN_TRACKS) return@async null
                    CommunityPlaylistData(
                        playlist = page.playlist.copy(
                            thumbnail = page.playlist.thumbnail ?: playlist.thumbnail,
                            author = page.playlist.author ?: playlist.author,
                        ),
                        songs = page.songs,
                    )
                }
            }.awaitAll().filterNotNull()
        }
        return fetched.take(MAX_RESULTS)
    }

    private fun diversify(candidates: List<Scored>): List<CommunityPlaylistData> {
        if (candidates.isEmpty()) return emptyList()
        val pool = candidates.sortedByDescending { it.score }.toMutableList()
        val picked = mutableListOf<Scored>()

        while (picked.size < MAX_RESULTS && pool.isNotEmpty()) {
            var bestIndex = 0
            var bestValue = -Double.MAX_VALUE
            pool.forEachIndexed { index, candidate ->
                val similarity = picked.maxOfOrNull { similarity(candidate, it) } ?: 0.0
                val value = candidate.score - 45.0 * similarity
                if (value > bestValue) {
                    bestValue = value
                    bestIndex = index
                }
            }
            picked += pool.removeAt(bestIndex)
        }

        return picked.map { it.data }
    }

    private fun similarity(a: Scored, b: Scored): Double {
        val union = a.artistKeys + b.artistKeys
        val artistSimilarity = if (union.isEmpty()) 0.0
        else (a.artistKeys.intersect(b.artistKeys).size.toDouble() / union.size)
        val authorSimilarity =
            if (a.author.isNotBlank() && a.author == b.author) 0.9 else 0.0
        return maxOf(artistSimilarity, authorSimilarity)
    }

    private fun addArtists(target: MutableMap<String, Double>, song: SongItem, weight: Double) {
        song.artists.forEach { artist ->
            val key = artist.name.lowercase().trim()
            if (key.isNotBlank()) target[key] = (target[key] ?: 0.0) + weight
        }
    }

    private fun normalize(values: Map<String, Double>): Map<String, Double> {
        if (values.isEmpty()) return emptyMap()
        val max = values.values.maxOrNull() ?: 0.0
        if (max <= 0.0) return values.mapValues { 0.0 }
        return values.mapValues { (_, value) -> value / max }
    }

    private fun parseViews(text: String?): Int {
        if (text.isNullOrBlank()) return 0
        if (!text.contains("view", ignoreCase = true)) return 0
        return parseScaledNumber(text) ?: 0
    }

    private fun parseScaledNumber(text: String): Int? {
        val match = Regex("([\\d.,]+)\\s*([KMB])?", RegexOption.IGNORE_CASE).find(text)
            ?: return null
        val number = match.groupValues[1].replace(",", "").toDoubleOrNull() ?: return null
        val multiplier = when (match.groupValues[2].uppercase()) {
            "K" -> 1_000.0
            "M" -> 1_000_000.0
            "B" -> 1_000_000_000.0
            else -> 1.0
        }
        return (number * multiplier).toInt()
    }

    private fun isAutoGenerated(playlistId: String): Boolean {
        if (playlistId.isBlank()) return true
        val prefixes = listOf("RD", "LM", "VLSE", "MPRE", "FEmusic", "OLAK5uy_")
        return prefixes.any { playlistId.startsWith(it) }
    }
}
